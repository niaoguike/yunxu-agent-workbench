"""Browser acceptance against a disabled-runner server. No real channel traffic."""
import os
import time
from pathlib import Path
from playwright.sync_api import sync_playwright, expect


def main():
    with sync_playwright() as pw:
        browser = pw.chromium.launch(channel=os.getenv("PLAYWRIGHT_CHANNEL", "msedge"), headless=True)
        page = browser.new_page(viewport={"width": 1600, "height": 1100})
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(os.getenv("WORKBENCH_BROWSER_URL", "http://127.0.0.1:8768"))
        page.get_by_role("button", name="创建账户", exact=True).click()
        page.get_by_label("邮箱").fill(f"routine-{time.time_ns()}@example.com")
        page.get_by_label("密码").fill("browser-check-password")
        page.locator(".dialog").get_by_role("button", name="保存", exact=True).click()
        page.get_by_role("button", name="创建第一个项目").click()
        page.get_by_label("名称", exact=True).fill("自动化与渠道验收")
        page.locator(".dialog").get_by_role("button", name="保存", exact=True).click()
        page.get_by_role("button", name="自动化", exact=True).click()
        panel = page.get_by_role("region", name="定时自动化")
        panel.get_by_label("名称", exact=True).fill("每日 CSV 分析")
        panel.get_by_label("执行内容").fill("分析项目中的 CSV，保存图表及检查结果")
        panel.get_by_label("执行周期").select_option("weekly")
        panel.get_by_label("星期", exact=True).select_option("0")
        panel.get_by_label("执行时间").fill("09:30")
        panel.get_by_role("button", name="创建自动化", exact=True).click()
        expect(panel.get_by_text("每日 CSV 分析 · 已暂停", exact=True)).to_be_visible()
        panel.get_by_role("button", name="立即执行一次").click()
        expect(panel.get_by_role("status")).to_contain_text("执行器不可用")
        panel.get_by_text("执行记录（1）", exact=True).click()
        panel.get_by_role("button", name="打开任务").click()
        expect(page.locator("header h2")).to_contain_text("每日 CSV 分析")
        panel.get_by_role("button", name="恢复", exact=True).click()
        expect(panel.get_by_text("每日 CSV 分析 · 已启用", exact=True)).to_be_visible()
        panel.get_by_role("button", name="暂停", exact=True).click()
        page.get_by_role("button", name="渠道", exact=True).click()
        channels = page.get_by_role("region", name="聊天渠道")
        channels.get_by_label("名称", exact=True).fill("Telegram 测试")
        channels.get_by_label("聊天 ID").fill("123")
        channels.get_by_label("允许的用户 ID").fill("42")
        channels.get_by_role("button", name="保存渠道连接").click()
        expect(channels.get_by_text("Telegram 测试 · telegram", exact=True)).to_be_visible()
        expect(channels.get_by_text("已停用 · 密钥未配置", exact=True)).to_be_visible()
        channels.get_by_text("连接配置说明", exact=True).click()
        expect(channels.locator("code")).to_contain_text("WORKBENCH_CHANNEL_")
        channels.get_by_role("button", name="验证机器人身份").click()
        expect(channels.get_by_role("alert")).to_contain_text("连接验证失败")
        channels.get_by_label("名称", exact=True).fill("Slack 测试")
        channels.get_by_label("平台").select_option("slack")
        channels.get_by_label("聊天 ID").fill("C123")
        channels.get_by_label("允许的用户 ID").fill("U42")
        channels.get_by_role("button", name="保存渠道连接").click()
        expect(channels.get_by_text("Slack 测试 · slack", exact=True)).to_be_visible()
        page.reload()
        expect(page.locator("header h2")).to_contain_text("每日 CSV 分析")
        page.get_by_role("button", name="渠道", exact=True).click()
        expect(page.get_by_text("Slack 测试 · slack", exact=True)).to_be_visible()
        page.get_by_role("button", name="扩展", exact=True).click()
        plugins = page.get_by_role("region", name="插件包管理")
        plugins.get_by_role("button", name="导入插件包").click()
        expect(plugins.get_by_text("csv-helper · 1.0", exact=True)).to_be_visible()
        expect(plugins.get_by_text("0 / 1 项已启用", exact=True)).to_be_visible()
        plugins.get_by_role("button", name="启用整个插件").click()
        expect(plugins.get_by_text("1 / 1 项已启用", exact=True)).to_be_visible()
        plugins.get_by_role("button", name="停用整个插件").click()
        expect(plugins.get_by_text("0 / 1 项已启用", exact=True)).to_be_visible()
        page.get_by_role("button", name="自动化", exact=True).click()
        panel = page.get_by_role("region", name="定时自动化")
        expect(panel.get_by_text("每日 CSV 分析 · 已暂停", exact=True)).to_be_visible()
        Path("output").mkdir(exist_ok=True)
        page.screenshot(path="output/automations-browser.png", full_page=True)
        assert not errors, errors
        browser.close()
        print("Automation browser flow passed: schedules, task records, channel configuration, reload, plugin lifecycle")


if __name__ == "__main__":
    main()
